def _reply(body: bytes) -> str:
    """Wrap ``body`` in a C3 query-response frame (checksum not validated)."""
    return (bytes([0xAA, 0x00, 0xC3, 0, 0, 0, 0, 0, 0, 0x03]) + body + b"\x00").hex()


def _with(body: bytes, **index_values: int) -> bytes:
    out = bytearray(body)
    for key, value in index_values.items():
        out[int(key.removeprefix("b"))] = value
    return bytes(out)


