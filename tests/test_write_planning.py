class _Transport:
    def __init__(self, replies: dict[str, str]) -> None:
        self.replies = replies
        self.sent: list[str] = []

    def __call__(self, command_hex: str) -> str:
        self.sent.append(command_hex)
        return self.replies.get(command_hex, ACK)


@pytest.mark.parametrize("row", list(ROWS.values()), ids=list(ROWS))
def test_dialect_write_table(row: Row) -> None:
    adapter = get_adapter(row.sn8)
    transport = _Transport(row.replies)

    def _plan_and_run() -> dict[str, Any]:
        plan = adapter.plan_write(row.command, row.ctx)
        return run_write_plan(plan, transport)

    if row.error is None:
        result = _plan_and_run()
        assert tuple(transport.sent) == row.sent
        assert result["sent"] == row.sent[-1]
        return

    error_type, match = row.error
    with pytest.raises(error_type, match=match):
        _plan_and_run()
    # Refusals never reach a SET: at most the fresh read the plan asked for.
    assert tuple(transport.sent) == row.sent


@pytest.mark.parametrize("sn8", [None, AQUAPURA_SN8, ATW_SN8, KJRH120L_SN8])
def test_plan_write_is_pure(sn8: str | None) -> None:
    """Planning never touches the transport; only ``run_write_plan`` does."""
    ctx = KJRH_CTX if sn8 == KJRH120L_SN8 else _atw_ctx()
    plan = get_adapter(sn8).plan_write(SetDhwTargetCommand(54), ctx)
    assert isinstance(plan, WritePlan)
    if plan.fresh_read is None:
        assert plan.command is not None
    else:
        assert plan.command is None
        assert plan.fresh_read.command == Q01


def test_kjrh_plans_never_read_and_c3_plans_always_read_fresh() -> None:
    kjrh = get_adapter(KJRH120L_SN8).plan_write(SetZoneTargetCommand(1, 50), KJRH_CTX)
    assert kjrh.fresh_read is None
    atw = get_adapter(ATW_SN8).plan_write(SetEcoModeCommand(True), _atw_ctx())
    assert atw.fresh_read is not None and atw.fresh_read.subtype == 0x07
    with pytest.raises(ValueError, match="fresh device read"):
        atw.resolve(None)


